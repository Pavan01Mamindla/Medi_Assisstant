(function () {
  "use strict";
  const form = document.getElementById("chat-form");
  if (!form) return;

  const log = document.getElementById("chat-log");
  const input = document.getElementById("chat-input");
  const send = document.getElementById("chat-send");
  const loading = document.getElementById("chat-loading");
  const errorBox = document.getElementById("chat-error");
  const csrf = document.querySelector('meta[name="csrf-token"]').content;
  const maxChars = parseInt(form.dataset.max, 10) || 1000;
  const history = [];

  const SOURCE_LABELS = {
    live: "AI-generated by Claude",
    demo: "Demo mode: predefined sample response, not AI-generated",
    emergency: "Safety message",
    error: "Service unavailable",
  };

  function addMessage(role, text, meta) {
    const wrap = document.createElement("div");
    wrap.className = "msg msg-" + role + (meta && meta.source === "emergency" ? " msg-emergency" : "");
    const label = document.createElement("span");
    label.className = "msg-label";
    label.textContent = role === "user" ? "You" : "MediAssist AI";
    wrap.appendChild(label);
    // textContent only: never insert model or user text as HTML.
    text.split(/\n{2,}/).forEach(function (para) {
      const p = document.createElement("p");
      p.textContent = para;
      wrap.appendChild(p);
    });
    if (meta && meta.source) {
      const tag = document.createElement("span");
      tag.className = "msg-source msg-source-" + meta.source;
      tag.textContent = SOURCE_LABELS[meta.source] || "";
      wrap.appendChild(tag);
    }
    log.appendChild(wrap);
    log.scrollTop = log.scrollHeight;
  }

  function setBusy(busy) {
    send.disabled = busy;
    input.disabled = busy;
    loading.hidden = !busy;
    if (!busy) input.focus();
  }

  function showError(msg) {
    errorBox.textContent = msg;
    errorBox.hidden = !msg;
  }

  input.addEventListener("keydown", function (e) {
    if (e.key === "Enter" && !e.shiftKey) {
      e.preventDefault();
      form.requestSubmit();
    }
  });

  form.addEventListener("submit", async function (e) {
    e.preventDefault();
    showError("");
    const text = input.value.trim();
    if (!text) { showError("Please type a question."); return; }
    if (text.length > maxChars) { showError("Please keep your message under " + maxChars + " characters."); return; }

    addMessage("user", text);
    history.push({ role: "user", content: text });
    input.value = "";
    setBusy(true);

    try {
      const res = await fetch("/api/chat", {
        method: "POST",
        headers: { "Content-Type": "application/json", "X-CSRFToken": csrf },
        body: JSON.stringify({ messages: history }),
      });
      const data = await res.json().catch(function () { return {}; });
      if (!res.ok) {
        history.pop();
        showError(data.error || "Sorry, something went wrong. Please try again.");
      } else {
        history.push({ role: "assistant", content: data.reply });
        addMessage("assistant", data.reply, data);
      }
    } catch (err) {
      history.pop();
      showError("Could not reach the server. Check your connection and try again.");
    } finally {
      setBusy(false);
    }
  });
})();
